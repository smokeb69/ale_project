  createFile(sessionId: string, name: string, content: string = ''): IDEFile | null {
    const session = this.sessions.get(sessionId);
    if (!session) return null;

    const ext = name.split('.').pop() || '';
    const language = this.detectLanguage(ext);

    const file: IDEFile = {
      name,
      content,
      language,
      lastModified: new Date(),
      version: 1,
      history: [],
    };

    session.files.set(name, file);
    
    const lines = content.split('\n').length;
    session.stats.linesOfCodeGenerated += lines;
    this.globalMetrics.totalCodeGenerated += lines;

    this.emit('fileCreated', { sessionId, file });
    return file;
  }

  updateFile(sessionId: string, name: string, content: string): IDEFile | null {
    const session = this.sessions.get(sessionId);
    if (!session) return null;

    const existing = session.files.get(name);
    if (!existing) return null;

    existing.history.push(existing.content);
    if (existing.history.length > 10) existing.history.shift();
    
    existing.content = content;
    existing.lastModified = new Date();
    existing.version++;

    this.emit('fileUpdated', { sessionId, file: existing });
    return existing;
  }

  deleteFile(sessionId: string, name: string): boolean {
    const session = this.sessions.get(sessionId);
    if (!session) return false;
    const deleted = session.files.delete(name);
    if (deleted) this.emit('fileDeleted', { sessionId, name });
    return deleted;
  }

  analyzeFile(sessionId: string, name: string): IDEFile['analysis'] | null {
    const session = this.sessions.get(sessionId);
    if (!session) return null;
    
    const file = session.files.get(name);
    if (!file) return null;

    // Simple analysis
    const analysis: IDEFile['analysis'] = {
      vulnerabilities: (file.content.match(/eval\(|exec\(|system\(/g) || []).length,
      complexity: Math.min(10, (file.content.match(/function|def|class/g) || []).length / 5),
      testCoverage: 0,
      dependencies: [...file.content.matchAll(/import\s+(\w+)|from\s+(\w+)/g)].map(m => m[1] || m[2]).filter(Boolean),
    };

    file.analysis = analysis;
    return analysis;
  }

  private detectLanguage(ext: string): string {
    const langMap: Record<string, string> = {
      ts: 'typescript', js: 'javascript', py: 'python', rs: 'rust',
      go: 'go', java: 'java', cpp: 'cpp', c: 'c', cs: 'csharp',
      rb: 'ruby', php: 'php', swift: 'swift', kt: 'kotlin',
      html: 'html', css: 'css', json: 'json', md: 'markdown',
      sql: 'sql', yaml: 'yaml', yml: 'yaml', xml: 'xml',
      sh: 'bash', ps1: 'powershell', bat: 'batch',
      asm: 'assembly', bin: 'binary', hex: 'hex',
    };
    return langMap[ext.toLowerCase()] || 'text';
  }

  // ============================================================================
  // VAULT & GRIMOIRE (Hidden Spellbook)
  // ============================================================================

  addSpell(sessionId: string, item: Omit<SpellItem, 'key'>): SpellItem | null {
    const session = this.sessions.get(sessionId);
    if (!session) return null;

    const key = nanoid(12);
    const spell: SpellItem = { ...item, key };
    
    if (item.isHidden) {
      session.grimoire.set(key, spell);
    } else {
      session.vault.set(key, spell);
    }

    this.emit('spellAdded', { sessionId, spell });
    return spell;
  }

  getSpell(sessionId: string, key: string): SpellItem | undefined {
    const session = this.sessions.get(sessionId);
    if (!session) return undefined;
    return session.vault.get(key) || session.grimoire.get(key);
  }

  searchSpells(sessionId: string, query: string, includeHidden: boolean = false): SpellItem[] {
    const session = this.sessions.get(sessionId);
    if (!session) return [];

    const q = query.toLowerCase();
    let items = Array.from(session.vault.values());
    
    if (includeHidden) {
      items = items.concat(Array.from(session.grimoire.values()));
    }

    return items.filter(item => 
      item.name.toLowerCase().includes(q) ||
      item.content.toLowerCase().includes(q) ||
      item.metadata.tags.some(tag => tag.toLowerCase().includes(q))
    );
  }

  revealGrimoire(sessionId: string, passphrase: string): SpellItem[] | null {
    // Simple passphrase check - in production use proper auth
    if (passphrase !== 'kimi-swarm-1337') return null;
    
    const session = this.sessions.get(sessionId);
    if (!session) return null;
    
    return Array.from(session.grimoire.values());
  }

  // ============================================================================
  // STATISTICS & METRICS
  // ============================================================================

  getStats(sessionId: string): SwarmSession['stats'] | null {
    const session = this.sessions.get(sessionId);
    return session ? session.stats : null;
  }

  getGlobalMetrics() {
    return { ...this.globalMetrics };
  }

  getDetailedStats(sessionId: string): object | null {
    const session = this.sessions.get(sessionId);
    if (!session) return null;

    return {
      session: {
        id: session.id,
        name: session.name,
        status: session.status,
        uptime: Date.now() - session.createdAt.getTime(),
      },
      agents: {
        total: session.agents.length,
        byRole: session.agents.reduce((acc, a) => {
          acc[a.role] = (acc[a.role] || 0) + 1;
          return acc;
        }, {} as Record<string, number>),
        avgPerformance: session.agents.reduce((sum, a) => sum + a.performance.successRate, 0) / session.agents.length,
      },
      tasks: {
        pending: session.queue.length,
        completed: session.completedTasks.length,
        failed: session.failedTasks.length,
        completionRate: session.stats.tasksCompleted / (session.stats.tasksCompleted + session.stats.tasksFailed) || 0,
      },
      files: {
        total: session.files.size,
        totalLines: session.stats.linesOfCodeGenerated,
      },
      vault: {
        visible: session.vault.size,
        hidden: session.grimoire.size,
      },
      stats: session.stats,
    };
  }

  startAutopilot(sessionId: string): boolean {
    const session = this.sessions.get(sessionId);
    if (!session) return false;

    this.stopAutopilot(sessionId);

    session.autonomy.autopilot = true;
    session.status = 'autopilot';

    const timer = setInterval(async () => {
      const s = this.sessions.get(sessionId);
      if (!s || !s.autonomy.autopilot) {
        this.stopAutopilot(sessionId);
        return;
      }

      // Auto-generate tasks if queue is low
      if (s.queue.length < 3) {
        const autoTasks = this.generateAutoTasks(s);
        for (const t of autoTasks) {
          this.enqueueTask(sessionId, t.text, t.priority, { ...t.metadata, autoGenerated: true });
        }
      }

      // Execute next task
      await this.stepSwarm(sessionId);
      
    }, 4000);

    this.autopilotTimers.set(sessionId, timer);
    this.emit('autopilotStarted', sessionId);
    return true;
  }

  private generateAutoTasks(session: SwarmSession): Array<{ text: string; priority: SwarmTask['priority']; metadata: SwarmTask['metadata'] }> {
    const tasks = [];
    const now = new Date().toLocaleTimeString();
    
    if (session.autonomy.autoMutate) {
      tasks.push({
        text: `Mutate and improve existing code @ ${now}`,
        priority: 'medium',
        metadata: { taskType: 'code', tags: ['mutation'] },
      });
    }
    
    if (session.autonomy.threatModeling) {
      tasks.push({
        text: `Update threat model with new TTPs @ ${now}`,
        priority: 'high',
        metadata: { taskType: 'analysis', tags: ['threat-model'] },
      });
    }
    
    if (session.autonomy.fuzzing) {
      tasks.push({
        text: `Fuzz test critical functions @ ${now}`,
        priority: 'medium',
        metadata: { taskType: 'code', tags: ['fuzzing'] },
      });
    }
    
    return tasks;
  }

  stopAutopilot(sessionId: string): boolean {
    const timer = this.autopilotTimers.get(sessionId);
    if (timer) {
      clearInterval(timer);
      this.autopilotTimers.delete(sessionId);
    }

    const session = this.sessions.get(sessionId);
    if (session) {
      session.autonomy.autopilot = false;
      session.status = 'paused';
    }

    this.emit('autopilotStopped', sessionId);
    return !!session;
  }

